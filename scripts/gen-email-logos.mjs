// One-off generator for the brief email logos (run with: node scripts/gen-email-logos.mjs).
// Rasterizes the service icon SVGs to transparent PNGs and base64-encodes the personal
// logo tile, writing them into src/lib/email/logos.ts. Email clients (Gmail/Outlook) don't
// render SVG, so the logos must ship as raster. sharp is already present transitively via
// Astro; we resolve it from the pnpm store so no extra dependency is needed.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(__dirname, '..');

// sharp lives in the pnpm store (transitive dep) — resolve it explicitly.
const sharp = require(resolve(appRoot, 'node_modules/.pnpm/sharp@0.34.5/node_modules/sharp'));

const ICONS = {
    bedrock: 'src/icons/Minecraft.astro',
    unity: 'src/icons/Unity.astro',
    flutter: 'src/icons/Flutter.astro',
    websites: 'src/icons/AstroIcon.astro',
};

const extractSvg = (file) => {
    const raw = readFileSync(resolve(appRoot, file), 'utf8');
    const m = raw.match(/<svg[\s\S]*<\/svg>/);
    if (!m) throw new Error(`No <svg> found in ${file}`);
    // Strip the Astro prop spread so it's valid standalone SVG.
    return m[0].replace(/\{\.\.\.Astro\.props\}/g, '');
};

const rasterize = async (svg) => {
    // High density so the small icon stays crisp at ~2x display size.
    const png = await sharp(Buffer.from(svg), { density: 384 })
        .resize(96, 96, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
        .png()
        .toBuffer();
    return png.toString('base64');
};

const run = async () => {
    const services = {};
    for (const [key, file] of Object.entries(ICONS)) {
        services[key] = await rasterize(extractSvg(file));
        console.log(`rasterized ${key.padEnd(9)} ${services[key].length} b64 chars`);
    }

    const personal = readFileSync(resolve(appRoot, 'public/img/Logo_dark.png')).toString('base64');
    console.log(`personal logo  ${personal.length} b64 chars`);

    const out = `// AUTO-GENERATED by scripts/gen-email-logos.mjs — do not edit by hand.
// Raster logos for the brief email (Gmail/Outlook don't render SVG). Stored as raw
// base64 PNG and attached by /api/brief via Resend with a contentId, then referenced
// as cid: in the HTML.
import type { ServiceKey } from '../../config/pricing';

// Self-contained navy "JV" tile — reads on both light and dark email backgrounds.
export const PERSONAL_LOGO_BASE64 =
    '${personal}';

// Transparent service marks, sized for a ~32px chip. Placed on a CSS-tinted dark chip.
export const SERVICE_ICON_BASE64: Record<ServiceKey, string> = {
    bedrock:
        '${services.bedrock}',
    unity:
        '${services.unity}',
    flutter:
        '${services.flutter}',
    websites:
        '${services.websites}',
};
`;

    const outPath = resolve(appRoot, 'src/lib/email/logos.ts');
    writeFileSync(outPath, out);
    console.log(`wrote ${outPath}`);
};

run().catch((e) => { console.error(e); process.exit(1); });
